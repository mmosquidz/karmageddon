/** The amount in the country's local currency, or null when no factor is published. */
export function localMoney(
  internationalDollars: number,
  countryCode: string,
): { amount: number; currency: string } | null {
  const power = PURCHASING_POWER[countryCode];
  if (!power) {
    return null;
  }
  const amount = Math.round(internationalDollars * power.factor);
  if (!Number.isSafeInteger(amount)) {
    return null;
  }
  return { amount, currency: power.currency };
}
